import assert from 'node:assert/strict';
import fs from 'node:fs';
import C from '../server/cases-contract.cjs';
const F = JSON.parse(fs.readFileSync(new URL('./fixtures/cases/fixtures.json', import.meta.url)));
const now = F.asOf, params = values => new URLSearchParams(values);
assert.deepEqual(C.summary(F.cases, now), F.expectedSummary);
assert.equal(C.listCases(F.cases, params({}), now).items.length, 8);
assert.equal(C.listCases(F.cases, params({ followUp: 'due' }), now).items.length, 2);
assert.equal(C.listCases(F.cases, params({ followUp: 'overdue' }), now).items.length, 1);
assert.equal(C.listCases(F.cases, params({ search: '080-000-0001' }), now).items[0].id, F.cases[0].id);
const first = C.listCases(F.cases, params({ scope: 'all', limit: '5' }), now);
const second = C.listCases(F.cases, params({ scope: 'all', limit: '5', cursor: first.nextCursor }), now);
assert.equal(new Set([...first.items, ...second.items].map(r => r.id)).size, 10);
assert.throws(() => C.listCases(F.cases, params({ cursor: first.nextCursor, status: 'new' }), now), /Cursor/);
const manual = C.createCase(F.requestExamples.manualCase, { id: 'manual-case-test', now });
assert.equal(manual.originalSubmission, null); assert.equal(manual.privacyReceipt, null);
assert.throws(() => C.createCase({ ...F.requestExamples.manualCase, consent: true }, { id: 'x', now }), /Unknown field/);
const patch = (r, changes, extra) => C.patchCase(r, { expectedVersion: r.version, changes, ...extra }, now);
assert.deepEqual(patch(manual, { workingNote: manual.workingNote }).record, manual);
const schedule = { dueAt: '2026-09-23T08:00:00Z', reminderEnabled: true };
const scheduled = patch(manual, { followUp: schedule }).record;
assert.equal(scheduled.followUpRevision, 1);
assert.equal(patch(scheduled, { workingNote: 'New note' }).record.followUpRevision, 1);
const ended = patch(scheduled, { status: 'closed_completed' }).record;
assert.equal(ended.followUp, null); assert.equal(ended.followUpRevision, 2); assert.equal(ended.closedAt, now);
assert.throws(() => patch(ended, { status: 'in_progress' }), /Reopen/);
const reopened = patch(ended, { status: 'in_progress' }, { reopen: true }).record;
assert.equal(reopened.closedAt, null); assert.equal(reopened.followUp, null);
assert.equal(patch(ended, { status: 'closed_declined' }).record.closedAt, ended.closedAt);
assert.throws(() => patch(manual, { status: 'won' }), /Invalid status/);
assert.throws(() => patch(manual, { originalSubmission: {} }), /Unknown field/);
assert.throws(() => C.patchCase(manual, { expectedVersion: 900, changes: { workingNote: 'overwrite' } }, now), /another session/);
const past = { ...scheduled, followUp: { dueAt: '2026-09-01T08:00:00.000Z', reminderEnabled: true } };
assert.equal(patch(past, { workingNote: 'Keep old date' }).record.followUpRevision, 1);
const off = patch(past, { followUp: { ...past.followUp, reminderEnabled: false } }).record;
assert.equal(off.followUpRevision, 2);
assert.throws(() => patch(off, { followUp: { ...off.followUp, reminderEnabled: true } }), /future time/);
assert.throws(() => patch(manual, { followUp: { dueAt: '2026-09-22', reminderEnabled: false } }), /UTC timestamp/);
const legacy = { name: 'Legacy demo', contact: 'ambiguous_line_or_phone', status: 'lost', createdAt: '2025-01-01T00:00:00Z', updatedAt: '2025-02-01T00:00:00Z', timeline: [{ text: 'Retained' }], ops: { tasks: { a: { dueAt: '2025-01-15T00:00:00Z' } } } };
const before = JSON.stringify(legacy), adapted = C.adaptCase('legacy', legacy);
assert.equal(adapted.status, 'closed_declined'); assert.equal(adapted.closedAt, null); assert.equal(adapted.privacyReceipt, null); assert.equal(adapted.contact.lineId, null); assert.equal(adapted.contact.rawContact, legacy.contact); assert.equal(JSON.stringify(legacy), before);
assert.throws(() => C.adaptCase('unknown', { ...legacy, status: 'mystery' }), /unmapped/);
assert.equal(C.summary([adapted], now).closedThisMonth, 0);
const boundary = { ...manual, followUp: { dueAt: '2026-09-21T17:00:00.000Z', reminderEnabled: false } };
assert.equal(C.listCases([boundary], params({ followUp: 'today' }), now).items.length, 1, 'Bangkok midnight belongs to Today.');
assert.equal(C.listCases([boundary], params({ followUp: 'overdue' }), now).items.length, 0);
assert.equal(C.summary([{ ...manual, followUp: { dueAt: now, reminderEnabled: false } }], now).followUpsDue, 1);
assert.equal(C.summary([{ ...manual, status: 'closed_completed', closedAt: '2026-08-31T17:00:00Z' }], now).closedThisMonth, 1);
assert.throws(() => patch(manual, { followUp: { dueAt: '2026-02-30T00:00:00Z', reminderEnabled: false } }), /UTC timestamp/);
console.log('Cases contract checks passed: fixtures, Bangkok metrics, filters/search/cursors, validation, version conflicts, transitions, reminder revisions, no-ops and non-destructive legacy projection.');
