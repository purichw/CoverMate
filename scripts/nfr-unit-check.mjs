import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createRequire } from 'node:module';
import { normalizeAdminRole, canEditContent, canEditRecords } from '../covermate-roles.mjs';
import { encryptBackup, decryptBackup } from './lib/encrypted-backup.mjs';
const require = createRequire(import.meta.url);
const { sanitizeEvent } = require('../server/telemetry.cjs');
for (const role of [undefined, null, '', 'typo', 'own.er', 'o-wner', ['owner'], {}, '__proto__', 'constructor']) assert.equal(normalizeAdminRole(role), 'none');
for (const role of ['owner', 'admin', 'administrator']) assert.equal(canEditContent(role), true);
for (const role of ['read-only', 'readonly', 'advisor', 'ops', 'unknown']) assert.equal(canEditContent(role), false);
assert.equal(canEditRecords('advisor'), true);
assert.equal(canEditRecords('readonly'), false);
const secret = randomBytes(32).toString('base64');
const snapshot = { documents: [{ path: 'sites/covermate/states/live', fields: { blank: { stringValue: '' }, thai: { stringValue: 'ทดสอบ' }, createdAt: { timestampValue: '2026-01-01T00:00:00Z' } } }] };
const ciphertext = encryptBackup(snapshot, secret);
assert.deepEqual(decryptBackup(ciphertext, secret), snapshot);
assert.throws(() => decryptBackup(ciphertext, randomBytes(32).toString('base64')));
const modified = Buffer.from(ciphertext); modified[modified.length - 1] ^= 1;
assert.throws(() => decryptBackup(modified, secret));
assert.equal(ciphertext.includes(Buffer.from('sites/covermate')), false);
const event = sanitizeEvent({ kind: 'runtime_error', route: '/?email=private@example.com', message: 'private@example.com', token: 'secret', contact: '0123', device: 'mobile' });
assert.deepEqual(event, { kind: 'runtime_error', route: 'other', device: 'mobile', value: undefined });
assert.equal(sanitizeEvent({ kind: 'private@example.com' }), null);
console.log('NFR units: fail-closed roles, authenticated encryption, and telemetry PII filtering passed.');
