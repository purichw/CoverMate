import assert from 'node:assert/strict';
import { versionChanges } from '../../src/visitor/editor-versions.js';

export async function checkVersionsWorkspace({page,panel,poll,shot,assertFit,baseUrl,readDraft,readVersions,setVersions,failHistory,failDraft,report}) {
  const seed=structuredClone(readVersions()), before=structuredClone(readDraft());
  const rows=()=>panel().locator('[data-version-id]');
  const dialog=()=>page.locator('[data-version-dialog]');
  const tab=()=>panel().getByRole('button',{name:'ประวัติเวอร์ชัน',exact:true});
  const refresh=async()=>{await panel().getByRole('button',{name:'โหลดประวัติใหม่',exact:true}).click();await poll(async()=>!await panel().getByText('กำลังโหลดประวัติเวอร์ชัน…',{exact:true}).count(),'History load completes');};
  const open=async id=>{await panel().locator(`[data-version-id="${id}"]`).getByRole('button',{name:'ดูรายละเอียด'}).click();await dialog().waitFor();};
  const close=async()=>{await dialog().getByRole('button',{name:'ปิดรายละเอียดเวอร์ชัน'}).click();await dialog().waitFor({state:'hidden'});};
  const confirm=()=>page.locator('[data-confirm-accept]');
  const choose=async(name,value)=>{await page.getByRole('combobox',{name,exact:true}).click();await page.getByRole('option',{name:value,exact:true}).click();};
  assert.equal(await page.evaluate(()=>performance.getEntriesByType('resource').some(entry=>entry.name.includes('/editor-versions.js'))),false,'History code is not fetched before opening its tab');
  let failModule=true;
  await page.route('**/assets/visitor/editor-versions.js*',route=>failModule?route.abort('failed'):route.continue());
  await tab().click();await panel().getByText('โหลดประวัติไม่สำเร็จ',{exact:true}).waitFor();
  assert.equal(await panel().getByRole('searchbox',{name:'ค้นหาประวัติเวอร์ชัน'}).count(),0,'Unloaded module never shows nonworking filter controls');
  failModule=false;await panel().getByRole('button',{name:'ลองใหม่',exact:true}).click();
  await poll(async()=>await rows().count()===5,'Failed module load is retryable');
  await page.unroute('**/assets/visitor/editor-versions.js*');
  report.checks.push('History module is lazy-loaded only on demand; a failed module fetch hides unavailable controls and Retry recovers.');
  await tab().click();await poll(async()=>await rows().count()===5,'Published history loaded');
  await assertFit('versions desktop');await shot('versions-desktop.png','Synthetic local published snapshots; current Draft/Live overview, filters and first page');
  await panel().getByRole('button',{name:'ตรงกับ Live 1',exact:true}).click();
  assert.equal(await rows().count(),1);assert.equal(await rows().first().getAttribute('data-version-id'),'local-v08');
  await open('local-v08');assert.equal(await dialog().locator('[data-version-restore]').isDisabled(),true);await close();
  await panel().getByRole('button',{name:'ทั้งหมด 8',exact:true}).click();
  await panel().getByRole('searchbox',{name:'ค้นหาประวัติเวอร์ชัน'}).fill('no-such-version');
  await panel().getByText('ไม่พบเวอร์ชันที่ตรงกัน',{exact:true}).waitFor();
  await panel().getByRole('button',{name:'ล้างตัวกรอง'}).click();
  await panel().getByRole('searchbox',{name:'ค้นหาประวัติเวอร์ชัน'}).fill('local-v07');
  assert.equal(await rows().count(),1);
  await panel().getByRole('searchbox',{name:'ค้นหาประวัติเวอร์ชัน'}).fill('');
  await choose('เรียงประวัติเวอร์ชัน','เก่าสุดก่อน');
  assert.equal(await rows().first().getAttribute('data-version-id'),'local-v01');
  await panel().getByRole('button',{name:'เวอร์ชันหน้าถัดไป'}).click();assert.equal(await rows().count(),3);
  await choose('เรียงประวัติเวอร์ชัน','ล่าสุดก่อน');
  await open('local-v07');
  assert.ok(await dialog().innerText().then(text=>text.includes('@history-1')&&text.includes('@CoverMate')&&text.includes('(ค่าว่าง)')),'Comparison displays real values including explicit empty');
  await choose('เปรียบเทียบเวอร์ชันกับ','Live ปัจจุบัน');
  await shot('versions-detail-desktop.png','Read-only selected snapshot versus Live values, including blank logo');
  await dialog().locator('[data-version-restore]').click();
  assert.ok(await page.locator('[data-admin-confirm]').innerText().then(text=>text.includes('Home, Motor')));
  await page.locator('[data-confirm-cancel]').click();
  assert.deepEqual(readDraft(),before,'Cancel cannot persist or modify Draft');
  failDraft(true);
  await dialog().locator('[data-version-restore]').click();await confirm().click();
  await page.getByText('กู้คืนไม่สำเร็จ · Draft เดิมยังอยู่',{exact:true}).waitFor();
  assert.deepEqual(readDraft(),before,'Failed restore retains remote Draft');
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('purich-draft-config-v3')).contact.lineId),'@CoverMate','Failed restore retains local Draft');
  failDraft(false);
  await dialog().locator('[data-version-restore]').click();await confirm().click();
  await poll(()=>readDraft().config.contact.lineId==='@history-1','Restore writes Draft');
  await dialog().waitFor({state:'hidden'});
  assert.equal(readDraft().config.brand.media.headerLogo.th,'');
  assert.ok(await page.locator('main').innerText().then(text=>text.includes('ตัวอย่างทดสอบประวัติ 1')),'Visitor canvas projects restored snapshot');
  await panel().locator('[data-editor-undo]').click();
  await poll(()=>readDraft().config.contact.lineId==='@CoverMate','Undo persists original Draft');
  await panel().locator('[data-editor-redo]').click();
  await poll(()=>readDraft().config.contact.lineId==='@history-1','Redo persists restored Draft');
  const historyBeforeReload=await page.evaluate(()=>JSON.parse(sessionStorage.getItem(Object.keys(sessionStorage).find(key=>key.startsWith('covermate-editor-history-v1:')))));
  await page.reload();await panel().waitFor();await tab().click();
  await poll(async()=>await rows().count()===5,'Reload retains history');
  assert.ok(await page.locator('main').innerText().then(text=>text.includes('ตัวอย่างทดสอบประวัติ 1')));
  if(await panel().locator('[data-editor-undo]').getAttribute('aria-disabled')==='true') {
    const next=await page.evaluate(()=>JSON.parse(sessionStorage.getItem(Object.keys(sessionStorage).find(key=>key.startsWith('covermate-editor-history-v1:')))));
    assert.fail('History reload mismatch: '+JSON.stringify(versionChanges(historyBeforeReload.entries[historyBeforeReload.cursor].snapshot,next.entries[next.cursor].snapshot)));
  }
  await panel().locator('[data-editor-undo]').click();
  await poll(()=>readDraft().config.contact.lineId==='@CoverMate','Undo survives reload');
  report.checks.push('Actual clicks: search, status filters, sorting, pagination, canonical value comparison, disabled identical restore, confirmation/cancel, failed write retention, Draft-only restore, Undo/Redo and reload.');
  failHistory(true);await refresh();await panel().getByText('โหลดประวัติไม่สำเร็จ',{exact:true}).waitFor();
  assert.equal(await rows().count(),5,'Fetch failure retains cached rows and an error');await shot('versions-error-desktop.png','Failed history fetch with retained cached list');
  failHistory(false);await panel().getByRole('button',{name:'ลองใหม่',exact:true}).click();
  await poll(async()=>!await panel().getByText('โหลดประวัติไม่สำเร็จ',{exact:true}).count(),'Retry clears error');
  setVersions([]);await refresh();await panel().getByText('ยังไม่มีประวัติการเผยแพร่',{exact:true}).waitFor();
  await shot('versions-empty-desktop.png','Real empty history state, not a network failure');
  setVersions(seed);await refresh();await poll(async()=>await rows().count()===5,'Seed restored');
  await page.goto(baseUrl+'/admin/content?page=motor');await panel().waitFor();await tab().click();
  await poll(async()=>await rows().count()===5,'Shared history is reachable from Motor');
  await page.goto(baseUrl+'/admin/content');await panel().waitFor();await tab().click();await poll(async()=>await rows().count()===5,'Home history');
  for(const width of [390,320,768]) {
    await page.setViewportSize({width,height:width===768?1024:844});
    await panel().locator('.cm-editor-scroll').evaluate(el=>el.scrollTop=0);
    await assertFit('versions '+width);await shot('versions-'+width+'.png','History summary and filters at '+width+'px');
    await rows().first().scrollIntoViewIfNeeded();await shot('versions-list-'+width+'.png','Responsive version records at '+width+'px');
    await open('local-v07');
    await choose('เปรียบเทียบเวอร์ชันกับ','Live ปัจจุบัน');
    const geometry=await dialog().evaluate(el=>({scroll:el.scrollWidth,width:el.clientWidth,x:el.getBoundingClientRect().x,right:el.getBoundingClientRect().right,viewport:innerWidth}));
    assert.ok(geometry.scroll<=geometry.width+1&&geometry.x>=0&&geometry.right<=geometry.viewport,'Dialog fits '+width);
    await shot('versions-detail-'+width+'.png','Mobile comparison with scrollable body and persistent restore actions');
    await dialog().getByRole('button',{name:'ปิดรายละเอียดเวอร์ชัน'}).focus();await page.keyboard.press('Shift+Tab');
    assert.equal(await dialog().locator('[data-version-restore]').evaluate(el=>el===document.activeElement),true,'Dialog traps focus');
    await page.keyboard.press('Escape');await dialog().waitFor({state:'hidden'});
    assert.equal(await panel().locator('[data-version-id="local-v07"] button').evaluate(el=>el===document.activeElement),true,'Escape restores row focus');
  }
  report.checks.push('History failure/retry and empty states are distinct; Home/Motor share history; 320/390/768px overview/list/detail fit with keyboard trap and focus restoration.');
}
