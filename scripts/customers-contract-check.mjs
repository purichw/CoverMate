import assert from 'node:assert/strict';
import * as M from '../customer-model.mjs';
import vault from '../server/customer-vault.cjs';
import { randomBytes } from 'node:crypto';
import { build } from 'esbuild';
import fs from 'node:fs';
const p = { ...M.emptyFields(M.PROFILE_FIELDS), firstName:'Synthetic', lastName:'Customer', phone:'0000000000' };
assert.equal(M.validateProfile(p).phone,p.phone);
assert.throws(()=>M.validateProfile({...p, birthDate:'2026-02-30'}));
assert.throws(()=>M.validateProfile({...p, passport:'UNSUPPORTED'}));
assert.throws(()=>M.validateProfile({...p, phone:''}));
const c = { ...M.emptyFields(M.CONSENT_FIELDS),status:'Granted',scopes:['profile'],occurredAt:'2026-01-01',channel:'Signed form',noticeVersion:'test-v1',noticeText:'Synthetic notice',evidence:'Synthetic paper reference' };
assert.equal(M.validateConsent(c).status,'Granted');
assert.throws(()=>M.validateConsent({...c, scopes:[]}));
assert.equal(M.hasConsent([c,{...c,status:'Withdrawn'}],'profile'),false);
assert.equal(M.hasConsent([c],'identity'),false);
const old = process.env.COVERMATE_CUSTOMER_VAULT_KEY;
delete process.env.COVERMATE_CUSTOMER_VAULT_KEY;
assert.equal(vault.available(),false);
assert.throws(()=>vault.seal(Buffer.from('fixture'),'fixture'));
process.env.COVERMATE_CUSTOMER_VAULT_KEY=randomBytes(32).toString('hex');
const sealed=vault.seal(Buffer.from('fixture'),'scope-a');
assert.equal(vault.open(sealed,'scope-a').toString(),'fixture');
assert.throws(()=>vault.open(sealed,'scope-b'));
assert.throws(()=>vault.open({...sealed,tag:Buffer.alloc(16).toString('base64')},'scope-a'));
if(old===undefined)delete process.env.COVERMATE_CUSTOMER_VAULT_KEY;else process.env.COVERMATE_CUSTOMER_VAULT_KEY=old;
assert.throws(()=>vault.validateFile({name:'bad.html',type:'image/png',data:Buffer.from('<script>alert(1)</script>').toString('base64')}));
const output=await build({entryPoints:['src/admin/customer-workspace.mjs'],outfile:'assets/admin-customers.js',bundle:true,format:'esm',target:['es2022'],minify:true,legalComments:'none',write:false});
assert.equal(fs.readFileSync('assets/admin-customers.js','utf8'),output.outputFiles[0].text,'Generated customer workspace is current.');
console.log('Customer schema, consent scope, private vault, file types and generated workspace checks passed.');
