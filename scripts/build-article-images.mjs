import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import sharp from 'sharp';

const root=new URL('../',import.meta.url);
const sources=['assets/articles/motor-road-v1.jpg','assets/articles/health-checklist-v1.jpg','assets/articles/family-planning-v1.webp','assets/brand/articles-reading-v1.webp'];
export async function buildArticleImages({check=false}={}){
  const manifest={};
  for(const source of sources){
    const input=await fs.readFile(new URL(source,root)),metadata=await sharp(input).metadata();
    const widths=[...new Set([320,640,800,1280,1600].map(width=>Math.min(width,metadata.width)))];
    const variants=[];
    for(const width of widths){
      const output=await sharp(input).resize({width,withoutEnlargement:true}).webp({quality:82}).toBuffer();
      const hash=createHash('sha256').update(output).digest('hex').slice(0,12);
      const src='/assets/articles/responsive/'+source.split('/').at(-1).replace(/\.[^.]+$/,'')+'-'+width+'-'+hash+'.webp';
      const file=new URL(src.slice(1),root);
      if(check){if(!(await fs.readFile(file)).equals(output))throw Error('Stale responsive article image: '+src);}
      else {await fs.mkdir(new URL('./',file),{recursive:true});await fs.writeFile(file,output);}
      variants.push({src,width});
    }
    manifest['/'+source]={width:metadata.width,height:metadata.height,variants};
  }
  const code='// Generated by scripts/build-article-images.mjs. Original assets remain intact.\nexport const LOCAL_ARTICLE_IMAGES = '+JSON.stringify(manifest,null,2)+';\n';
  const file=new URL('article-image-assets.mjs',root);
  if(check){if(await fs.readFile(file,'utf8')!==code)throw Error('Stale article image manifest');}
  else await fs.writeFile(file,code);
}
