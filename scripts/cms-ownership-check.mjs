import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { importCoverMateContract } from './lib/contract-loader.mjs';
import { buildVisitorRuntime } from './lib/visitor-source.mjs';
import { planCmsMigration } from './migrate-cms-content.mjs';
import { toFirestoreFields, fromFirestoreFields } from './lib/uat-env.mjs';

const contract = await importCoverMateContract();
const { sanitizeMotorCountConfig: sanitize, migrateCmsContent, resolveCmsContent, cmsGet, cmsSet, motorInsurerLogoCount } = contract;
const defaults = JSON.parse(vm.runInNewContext(fs.readFileSync('src/visitor/defaults.js', 'utf8') + '\nJSON.stringify(DEFAULTS)'));
const legacy = structuredClone(defaults);
legacy.contact.phone = '08X-XXX-XXXX';
legacy.contact.email = 'purich@example.com';
delete legacy.sections.find(s => s.id === 'hero').cta2href;
legacy.sections.find(s => s.id === 'insurers').items[12].logo = 'assets/ins/13-thaivivat.png';
const migrated = sanitize(legacy);
assert.deepEqual(contract.sanitizeMotorCountText({ 'footer:18:th': 'purich@example.com', 'hero:0:th': 'ผมพร้อมช่วยครับ' }, migrated), { 'hero:0:th': 'ผมพร้อมช่วยครับ' });
assert.equal(migrated.cmsContentVersion, 2);
assert.equal(migrated.contact.phone, '');
assert.equal(migrated.contact.email, '');
assert.equal(migrated.licences.life.number, '6401006221');
assert.equal(migrated.licences.nonLife.number, '6804008544');
assert.equal(migrated.licences.broker.number, 'ว00287/2534');
assert.equal(migrated.sections.find(s => s.id === 'hero').cta2href, '#fit');
assert.ok(JSON.stringify(migrated).includes('{{lifeLicence}}'));
assert.equal(migrated.sections.find(s => s.id === 'insurers').items[12].logo, 'assets/ins/13-aioi.png');
assert.deepEqual(migrateCmsContent(migrated), migrated, 'Migration is idempotent');
assert.equal(legacy.contact.phone, '08X-XXX-XXXX', 'Migration does not mutate source');

const edited = structuredClone(migrated);
edited.licences.life.number = '9000000001';
edited.licences.nonLife.number = '9000000002';
edited.licences.broker.number = 'TEST-3';
edited.brand.credential = { th: 'ข้อความจริงจากเจ้าของ', en: 'Owner supplied credential' };
edited.header.nav = [{ label: { th: 'เมนูของเรา', en: '' }, href: '#faq' }];
edited.header.cta = { th: 'คุยกับเรา', en: 'Talk with us' };
edited.footer.legal.en = 'Owner legal: {{lifeLicence}} / {{nonLifeLicence}} / {{brokerLicence}}';
edited.sections.find(s => s.id === 'guides').th.body = 'ผมพร้อมช่วยครับ';
edited.sections.find(s => s.id === 'insurers').items = [{ th: { name: 'บริษัทใหม่' }, en: { name: 'New insurer' }, logo: '' }];
edited.sections.find(s => s.id === 'insurers').cards = [];
edited.motorPage.nav = [];
edited.motorPage.sections = [];
edited.sections.find(s => s.id === 'hero').cta2href = '';
edited.sections.find(s => s.id === 'hero').claimHref = '';
for (const key of ['phone', 'email', 'lineUrl', 'facebookUrl']) edited.contact[key] = '';
edited.brand.advisorLogo = '';
for (const field of contract.CMS_CONTENT_FIELDS.filter(field => field.media)) {
  if (field.localized) for (const lang of ['th', 'en']) cmsSet(edited, field.path + '.' + lang, '');
  else cmsSet(edited, field.path, '');
}
const clean = sanitize(edited);
assert.deepEqual(clean.header, edited.header);
assert.deepEqual(clean.brand.credential, edited.brand.credential);
assert.equal(clean.sections.find(s => s.id === 'guides').th.body, 'ผมพร้อมช่วยครับ');
assert.equal(motorInsurerLogoCount(clean), 0);
assert.match(clean.sections.find(s => s.id === 'hero').th.body, /บริษัทประกันภัย 0 แห่ง/);
assert.equal(clean.sections.find(s => s.id === 'insurers').items[0].logo, '');
assert.equal(clean.sections.find(s => s.id === 'insurers').cards.length, 0);
assert.deepEqual(clean.motorPage.sections, []);
assert.deepEqual(clean.motorPage.nav, []);
assert.equal(resolveCmsContent(clean.footer.legal.en, clean), 'Owner legal: 9000000001 / 9000000002 / TEST-3');
for (const key of ['phone', 'email', 'lineUrl', 'facebookUrl']) assert.equal(clean.contact[key], '');
for (const field of contract.CMS_CONTENT_FIELDS.filter(field => field.media)) {
  for (const path of field.localized ? ['th', 'en'].map(lang => field.path + '.' + lang) : [field.path]) assert.equal(cmsGet(clean, path), '', path);
}
assert.equal(clean.brand.advisorLogo, '');
assert.equal(sanitize({ ...clean, header: { ...clean.header, nav: [{ label: { th: 'Unsafe', en: '' }, href: 'javascript:alert(1)' }] } }).header.nav[0].href, '');
const customBeforeMigration = { licences: { life: { number: 'KEEP' } }, brand: { media: { mark: '' } } };
assert.equal(migrateCmsContent(customBeforeMigration).licences.life.number, 'KEEP');
assert.equal(migrateCmsContent(customBeforeMigration).brand.media.mark, '');

const v1 = structuredClone(migrated);
v1.cmsContentVersion = 1;
delete v1.publicCopy;
delete v1.lifeFocus;
v1.sections.find(s => s.id === 'insurers').items[0].logo = 'assets/ins/13-thaivivat.png';
v1.footer.legal.en = 'Owner chose literal 6401006221';
v1.publicCopy = { calcSpending: { th: 'Owner spending', en: '' } };
v1.cmsLegacyCopy = [];
const v2 = sanitize(v1);
assert.equal(v2.cmsContentVersion, 2);
assert.deepEqual(v2.publicCopy.calcSpending, { th: 'Owner spending', en: '' });
assert.ok(!v2.cmsLegacyCopy.includes('publicCopy.calcSpending.en'));
assert.ok(v2.cmsLegacyCopy.includes('lifeFocus.title.th'));
assert.equal(v2.sections.find(s => s.id === 'insurers').items[0].logo, 'assets/ins/13-thaivivat.png', 'v2 does not repeat the v0 insurer replacement');
assert.equal(v2.footer.legal.en, 'Owner chose literal 6401006221', 'v2 does not rewrite v1 owner copy');
assert.deepEqual(migrateCmsContent(v2), v2);
const pendingEdit = contract.sanitizeStateDoc({ config: v2, text: { 'cms:publicCopy.calcSpending.en': '', 'cms:lifeFocus.title.th': 'แก้ก่อนออกจากหน้า', 'hero:0:th': 'Keep unrelated copy' } });
assert.equal(pendingEdit.config.publicCopy.calcSpending.en, '');
assert.equal(pendingEdit.config.lifeFocus.title.th, 'แก้ก่อนออกจากหน้า');
assert.deepEqual(pendingEdit.text, { 'hero:0:th': 'Keep unrelated copy' });
assert.ok(!pendingEdit.config.cmsLegacyCopy.includes('lifeFocus.title.th'));
const blankCopy = structuredClone(v2);
for (const field of contract.CMS_CONTENT_FIELDS.filter(field => field.localized)) {
  cmsSet(blankCopy, field.path + '.th', 'ข้อความจากเจ้าของ');
  cmsSet(blankCopy, field.path + '.en', '');
}
const roundTrip = sanitize(blankCopy);
for (const field of contract.CMS_CONTENT_FIELDS.filter(field => field.localized && !field.media)) {
  assert.equal(cmsGet(roundTrip, field.path + '.th'), 'ข้อความจากเจ้าของ', field.path);
  assert.equal(cmsGet(roundTrip, field.path + '.en'), '', field.path);
}

const sandbox = { URL, DCLogic: class {}, window: { CoverMateContract: contract, location: { origin: 'http://localhost', pathname: '/' } } };
vm.runInNewContext(buildVisitorRuntime() + '\nthis.Component = Component;', sandbox);
const owner = sandbox.Component.prototype;
const normalized = JSON.parse(JSON.stringify(owner.normalizeConfig.call(owner, clean)));
assert.equal(normalized.brand.advisorLogo, '');
assert.equal(normalized.sections.find(s => s.id === 'hero').cta2href, '');
assert.equal(normalized.sections.find(s => s.id === 'hero').claimHref, '');
assert.deepEqual(normalized.header, clean.header);
assert.deepEqual(normalized.motorPage.sections, []);
assert.equal(owner.buildMotorPageSections.call(owner, normalized).length, 0);
assert.equal(normalized.sections.find(s => s.id === 'insurers').items[0].logo, '');
assert.equal(owner.companyLogoCount(normalized), 0);
