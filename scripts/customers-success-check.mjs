async function fill(values = {}) {
  const data = { firstName: 'สมชาย', lastName: 'ข้อมูลจำลอง', email: `success-${Date.now()}@example.test`, 'consent.occurredAt': '2026-01-01', 'consent.noticeVersion': 'CM-QA-v1', 'consent.noticeText': 'ข้อมูลจำลองเพื่อทดสอบหน้าสำเร็จ ไม่ใช่ความยินยอมจริง', 'consent.evidence': 'Synthetic QA evidence', ...values };
  for (const details of await form.locator('[data-customer-section]').all()) if (!await details.evaluate(el => el.open)) await details.locator('summary').click();
  for (const [name, value] of Object.entries(data)) await form.locator(`[name="${name}"]`).fill(value);
  await form.locator('[name="consent.channel"]').selectOption('Signed form', { force: true });
  await form.locator('[type=submit]').click();
  await form.locator('[data-customer-review]:not([hidden])').waitFor();
  return data;
}
